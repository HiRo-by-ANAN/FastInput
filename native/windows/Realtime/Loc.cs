    private static string _language = DetectLanguage(CultureInfo.CurrentUICulture.Name);
    public static string Language => Volatile.Read(ref _language);
    public static CultureInfo Culture => CultureInfo.GetCultureInfo(Language);
    public static event Action? LanguageChanged;

    public static string DetectLanguage(string? culture)
    {
        if (culture?.StartsWith("ja", StringComparison.OrdinalIgnoreCase) == true) return "ja";
        if (culture?.StartsWith("en", StringComparison.OrdinalIgnoreCase) == true) return "en";
        return "zh-Hant";
    }

    public static bool IsSupported(string? code) => code is "zh-Hant" or "ja" or "en";
    public static bool SetLanguage(string code)
    {
        if (!IsSupported(code)) return false;
        if (Interlocked.Exchange(ref _language, code) != code) LanguageChanged?.Invoke();
        return true;
    }

    public static string T(string key, params object?[] values)
    {
        var template = Dictionaries[Language].GetValueOrDefault(key) ?? Dictionaries["zh-Hant"].GetValueOrDefault(key) ?? key;
        return Regex.Replace(template, @"\{value(\d+)\}", match =>
        {
            var index = int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture);
            if (index >= values.Length) return match.Value;
            var value = values[index];
            return value is byte or sbyte or short or ushort or int or uint or long or ulong or float or double or decimal
                ? ((IFormattable)value).ToString("N0", Culture) : value?.ToString() ?? "";
        });
    }

    // Static safety explanations may have been captured before a language change.
    public static string? Localize(string? message)
    {
        if (message is null) return null;
        foreach (var dictionary in Dictionaries.Values)
            foreach (var pair in dictionary)
                if (pair.Value == message) return T(pair.Key);
        return message;
    }
    public static string Reason(string? code) => string.IsNullOrEmpty(code) ? "" : T("reason." + code);
